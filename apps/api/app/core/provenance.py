"""Data provenance: the contract that keeps simulated data honestly labelled.

Every response assembled from a provider (blood banks, routing, IoT, ledger, LLM,
ML, verification) must carry a ``SourceMeta``. The web UI renders a visible
"Simulated" badge whenever ``simulated`` is true. This is a frozen foundation contract.
"""

from __future__ import annotations

from datetime import datetime
from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field, computed_field


class SourceKind(StrEnum):
    """What kind of source produced the data."""

    INTERNAL = "internal"  # data entered/owned inside VEYRA itself
    SIMULATED = "simulated"  # generated by a VEYRA simulator or mock provider
    SYNTHETIC = "synthetic"  # derived from synthetic datasets (e.g. ML trained on synthetic data)
    EXTERNAL = "external"  # a real third-party integration


class SourceMeta(BaseModel):
    model_config = ConfigDict(frozen=True)

    provider: str = Field(description="Provider identifier, e.g. 'mock_blood_bank'")
    kind: SourceKind
    fetched_at: datetime | None = None
    note: str | None = Field(default=None, description="Human-readable disclosure, if any")

    @computed_field  # type: ignore[prop-decorator]
    @property
    def simulated(self) -> bool:
        return self.kind in (SourceKind.SIMULATED, SourceKind.SYNTHETIC)
